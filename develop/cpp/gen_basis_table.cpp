// Offline generator of the embedded bench data (NOTES.md section 10):
//   gen_basis_table <out.h>
// writes the problems A, B, TINY and the stable-basis table of TINY as flash constants
// (LQOCP_FLASH, e.g. PROGMEM on a Teensy): one basis per set of active rows (basis_key), which
// covers every active set, so any x0 (MPC) is served.
#include <cmath>
#include <cstdio>
#include <cstring>
#include <string>

#include "case_data.h"
#include "lqocp.hpp"

static lqocp::GSolver g_solver;
static lqocp::BasisBuilder g_basis;

static void to_problem(const LqocpCaseData& cd, lqocp::Problem& p) {
    std::memset(&p, 0, sizeof(p));
    p.m = 4;
    for (int j = 0; j < 4; ++j) p.orders[j] = cd.orders[j];
    p.T = cd.T;
    for (int i = 0; i < 12; ++i) { p.x0[i] = cd.x0[i]; p.xf[i] = cd.xf[i]; }
    p.has_bounds = cd.has_bounds;
    for (int r = 0; r < 4; ++r) {
        for (int j = 0; j < 4; ++j) p.M[r][j] = cd.Umap[r * 4 + j];
        p.lo[r] = cd.has_bounds ? cd.u_min[r] : -HUGE_VAL;
        p.hi[r] = cd.has_bounds ? cd.u_max[r] : HUGE_VAL;
    }
    p.has_cost = cd.has_cost;
    p.has_Qf = cd.has_Qf;
    for (int i = 0; i < 144; ++i) { p.Q[i / 12][i % 12] = cd.Q[i]; p.Qf[i / 12][i % 12] = cd.Qf[i]; }
    for (int i = 0; i < 16; ++i) p.R[i / 4][i % 4] = cd.R[i];
}

static void arr(FILE* f, const char* name, const double* v, int n) {
    std::fprintf(f, "static const double %s[%d] LQOCP_FLASH = {", name, n > 0 ? n : 1);
    for (int i = 0; i < n; ++i) std::fprintf(f, "%s%.17g", i ? "," : "", v[i]);
    if (n == 0) std::fprintf(f, "0");
    std::fprintf(f, "};\n");
}

static void num(FILE* f, double v) {
    if (std::isinf(v)) std::fprintf(f, "%sHUGE_VAL", v < 0 ? "-" : "");
    else std::fprintf(f, "%.17g", v);
}

static void problem(FILE* f, const lqocp::Problem& p) {
    std::fprintf(f, "{%d, {%d, %d, %d, %d}, ", p.m, p.orders[0], p.orders[1], p.orders[2], p.orders[3]);
    num(f, p.T);
    const double* blocks[2] = {p.x0, p.xf};
    for (int b = 0; b < 2; ++b) {
        std::fprintf(f, ", {");
        for (int i = 0; i < 12; ++i) { std::fprintf(f, i ? "," : ""); num(f, blocks[b][i]); }
        std::fprintf(f, "}");
    }
    std::fprintf(f, ", %d, {", p.has_bounds);
    for (int i = 0; i < 16; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.M[i / 4][i % 4]); }
    std::fprintf(f, "}, {");
    for (int i = 0; i < 4; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.lo[i]); }
    std::fprintf(f, "}, {");
    for (int i = 0; i < 4; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.hi[i]); }
    std::fprintf(f, "}, %d, {", p.has_cost);
    for (int i = 0; i < 144; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.Q[i / 12][i % 12]); }
    std::fprintf(f, "}, {");
    for (int i = 0; i < 16; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.R[i / 4][i % 4]); }
    std::fprintf(f, "}, %d, {", p.has_Qf);
    for (int i = 0; i < 144; ++i) { std::fprintf(f, i ? "," : ""); num(f, p.Qf[i / 12][i % 12]); }
    std::fprintf(f, "}}");
}

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: %s <out.h>\n", argv[0]);
        return 2;
    }
    static lqocp::Problem probs[3];
    const char* names[3] = {"A", "B", "TINY"};
    for (int k = 0; k < 3; ++k)
        for (int i = 0; i < LQOCP_NUM_CASES; ++i)
            if (std::string(LQOCP_CASES[i].name) == names[k]) to_problem(LQOCP_CASES[i], probs[k]);
    const lqocp::Problem& tiny = probs[2];
    if (!g_solver.setup(tiny, lqocp::BasisBuilder::fn, &g_basis)) return 3;
    g_basis.attach(&g_solver);
    for (int i = 0; i < g_solver.nsets(); ++i)
        if (!g_basis.get(g_solver.set(i))) std::fprintf(stderr, "no basis for set %x\n", g_solver.set(i));
    FILE* f = std::fopen(argv[1], "w");
    if (!f) return 1;
    std::fprintf(f, "// Generated by develop/cpp/gen_basis_table.cpp. Do not edit.\n");
    std::fprintf(f, "#include <math.h>\n#include \"lqocp.hpp\"\n#ifndef LQOCP_FLASH\n#define LQOCP_FLASH\n#endif\n");
    std::fprintf(f, "static const lqocp::Problem BENCH_PROB[3] LQOCP_FLASH = {  // A, B, TINY\n");
    for (int k = 0; k < 3; ++k) { problem(f, probs[k]); std::fprintf(f, ",\n"); }
    std::fprintf(f, "};\n");
    const int n2 = g_solver.n2(), nb = g_basis.count();
    for (int s = 0; s < nb; ++s) {
        const lqocp::SetBasis& b = g_basis.at(s);
        char nm[32];
        std::snprintf(nm, sizeof nm, "TB_W%d", s); arr(f, nm, b.W, n2 * n2);
        std::snprintf(nm, sizeof nm, "TB_Wi%d", s); arr(f, nm, b.Wi, n2 * n2);
        std::snprintf(nm, sizeof nm, "TB_re%d", s); arr(f, nm, b.re, n2);
        std::snprintf(nm, sizeof nm, "TB_im%d", s); arr(f, nm, b.im, n2);
        std::snprintf(nm, sizeof nm, "TB_Tc%d", s); arr(f, nm, b.Tc, b.nc * b.nc);
        std::snprintf(nm, sizeof nm, "TB_cs%d", s); arr(f, nm, b.cs, n2);
    }
    std::fprintf(f, "static const int TINY_NBASES = %d;\n", nb);
    std::fprintf(f, "static const lqocp::SetBasis TINY_BASES[%d] LQOCP_FLASH = {\n", nb);
    for (int s = 0; s < nb; ++s) {
        const lqocp::SetBasis& b = g_basis.at(s);
        std::fprintf(f, "  {%u, %u, %u, %u, %u, %.17g, TB_W%d, TB_Wi%d, TB_re%d, TB_im%d, TB_Tc%d, TB_cs%d},\n",
                     b.S, b.ns, b.nc, b.nz, b.ni, b.tcn, s, s, s, s, s, s);
    }
    std::fprintf(f, "};\n");
    std::fclose(f);
    std::printf("%d sets written to %s\n", nb, argv[1]);
    return 0;
}
