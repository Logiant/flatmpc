"""Generate case_data.h (C header with quad_problem.CASES and TINY_CASE) at full double precision.
Usage: python3 gen_case_data.py [out.h]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "problem"))
import numpy as np  # noqa: E402
import quad_problem as qp  # noqa: E402


def arr(v):
    return "{" + ", ".join("%.17g" % float(x) for x in np.ravel(v)) + "}"


def main(out):
    L = ["/* Auto-generated by gen_case_data.py from problem/quad_problem.py. Do not edit. */",
         "#ifndef LQOCP_CASE_DATA_H", "#define LQOCP_CASE_DATA_H", "",
         "typedef struct {", "  const char* name;", "  int n, m;", "  int orders[4];", "  double T;",
         "  double x0[12];", "  double xf[12];", "  int has_bounds;",
         "  double Umap[16]; /* row-major, u = Umap v */", "  double u_min[4];", "  double u_max[4];",
         "  int has_cost;     /* 0: energy cost (Q=0, R=I, fixed endpoint) */",
         "  double Q[144];", "  double R[16];", "  int has_Qf;       /* 0: fixed endpoint */",
         "  double Qf[144];", "} LqocpCaseData;", ""]
    cases = dict(qp.CASES)
    cases["TINY"] = qp.TINY_CASE
    L.append("static const LqocpCaseData LQOCP_CASES[] = {")
    for name, cs in cases.items():
        M = np.eye(4) if cs.get("Umap") is None else cs["Umap"]
        hb = cs.get("u_min") is not None
        lo = cs["u_min"] if hb else np.zeros(4)
        hi = cs["u_max"] if hb else np.zeros(4)
        hc = any(cs.get(k) is not None for k in ("Q", "R", "Qf"))
        Q = cs.get("Q") if cs.get("Q") is not None else np.zeros((12, 12))
        R = cs.get("R") if cs.get("R") is not None else np.eye(4)
        hq = cs.get("Qf") is not None
        Qf = cs["Qf"] if hq else np.zeros((12, 12))
        L.append("  {\"%s\", %d, %d, %s, %.17g, %s, %s, %d, %s, %s, %s, %d, %s, %s, %d, %s}," % (
            name, qp.NX, qp.NU, "{" + ", ".join(str(k) for k in qp.CHAIN_ORDERS) + "}",
            cs["T"], arr(cs["x0"]), arr(cs["xf"]), int(hb), arr(M), arr(lo), arr(hi),
            int(hc), arr(Q), arr(R), int(hq), arr(Qf)))
    L += ["};", "static const int LQOCP_NUM_CASES = %d;" % len(cases), "", "#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "case_data.h"))
