"""Writes src/mpc_data.h for the MPC closed-loop / knot-sweep bench (run from the repo root with validate/.venv).

Exact model: the flat integrator chains (problem/quad_problem.py). TinyMPC gets the exact ZOH discretisation of it in
physical coordinates for each knot count N (dt = T/(N-1)), and our solver the matching terminal weight
Qf(N) = dt*(DARE(Ad, Bd, rho I, R + rho I) - rho I) (TinyMPC's single-rho cache with Q = 0), mapped to flat coordinates.
"""
import sys
import numpy as np
from scipy.linalg import expm, solve_discrete_are
sys.path.insert(0, "problem")
import quad_problem as qp

T, RHO, R = 0.45, 5.0, 4.0 * np.eye(4)
SWEEP = [10, 15, 20, 30, 45, 60, 90]
Minv = np.linalg.inv(qp.Umap)


def disc(dt):
    n, m = 12, 4
    E = np.zeros((n + m, n + m)); E[:n, :n] = qp.Af; E[:n, n:] = qp.Bf
    E = expm(E * dt)
    Ad = qp.Tf2p @ E[:n, :n] @ qp.Tp2f
    Bd = qp.Tf2p @ E[:n, n:] @ Minv            # physical thrust input
    return Ad, Bd


def qf_flat(dt):
    Ad, Bd = disc(dt)
    P = solve_discrete_are(Ad, Bd, RHO * np.eye(12), R + RHO * np.eye(4))
    return qp.Tf2p.T @ (dt * (P - RHO * np.eye(12))) @ qp.Tf2p


Ad10, Bd10 = disc(0.05)
print("exact vs published Ad/Bd (N=10):", np.abs(Ad10 - qp.Ad).max(), np.abs(Bd10 - qp.Bd).max(), file=sys.stderr)

# physical x_i = PS[i] * s[PF[i]] (Tf2p has one nonzero per row)
PF = [int(np.flatnonzero(qp.Tf2p[i])[0]) for i in range(12)]
PS = [qp.Tf2p[i, PF[i]] for i in range(12)]
assert np.allclose(qp.Tf2p, np.array([[PS[i] if j == PF[i] else 0 for j in range(12)] for i in range(12)]))

# x0: TINY's, then 10 random realistic hover deviations (seed 1): position +-1.5 m, roll/pitch Rodrigues +-0.2,
# yaw +-0.3, velocity +-0.5 m/s, body rates +-1 rad/s
rng = np.random.default_rng(1)
lim = np.array([1.5, 1.5, 1.5, 0.2, 0.2, 0.3, 0.5, 0.5, 0.5, 1, 1, 1])
X0 = [qp.X0] + [rng.uniform(-lim, lim) for _ in range(10)]


def arr(a):
    return "{" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "}"


out = ["// Generated by teensy/mpc_bench/gen_data.py; do not edit.", "#pragma once",
       "#ifndef DATA_FLASH", "#define DATA_FLASH", "#endif",
       f"static const int NSW = {len(SWEEP)}, NX0 = {len(X0)};",
       f"static const int SW_N[NSW] = {{{', '.join(map(str, SWEEP))}}};",
       f"static const int PF[12] = {{{', '.join(map(str, PF))}}};",
       f"static const double PS[12] = {arr(PS)};",
       f"static const double UMAP[16] = {arr(qp.Umap)};",
       f"static const double UMINV[16] = {arr(Minv)};",
       f"static const double RFLAT[16] = {arr(qp.Umap.T @ R @ qp.Umap)};",
       f"static const double X0F[NX0][12] DATA_FLASH = {{{', '.join(arr(qp.phys_to_flat(x)) for x in X0)}}};"]
ads, bds, qfs = zip(*[(*disc(T / (n - 1)), qf_flat(T / (n - 1))) for n in SWEEP])
out += [f"static const double SW_AD[NSW][144] DATA_FLASH = {{{', '.join(map(arr, ads))}}};",
        f"static const double SW_BD[NSW][48] DATA_FLASH = {{{', '.join(map(arr, bds))}}};",
        f"static const double SW_QF[NSW][144] DATA_FLASH = {{{', '.join(map(arr, qfs))}}};"]
open("teensy/mpc_bench/src/mpc_data.h", "w").write("\n".join(out) + "\n")
q10 = qfs[0]
print("Qf(N) rel. change vs N=10:", [f"{np.abs(q - q10).max() / np.abs(q10).max():.3g}" for q in qfs], file=sys.stderr)
